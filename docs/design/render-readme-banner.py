#!/usr/bin/env python3
"""Render the README cover from the canonical mark using only the standard library."""

from pathlib import Path
import xml.etree.ElementTree as ET


def main():
    directory = Path(__file__).resolve().parent
    namespace = "http://www.w3.org/2000/svg"
    ET.register_namespace("", namespace)
    mark = ET.parse(directory / "echidna-mark.svg").getroot()
    for child in list(mark):
        if child.tag.rsplit("}", 1)[-1] in {"title", "desc", "view"}:
            mark.remove(child)
    mark.attrib.pop("aria-labelledby", None)
    mark.set("aria-hidden", "true")
    for key, value in {"x": "64", "y": "48", "width": "288", "height": "288"}.items():
        mark.set(key, value)
    logo = ET.tostring(mark, encoding="unicode")
    banner = f'''<svg xmlns="{namespace}" width="1280" height="400" viewBox="0 0 1280 400" role="img" aria-labelledby="cover-title cover-description">
  <!-- Generated by render-readme-banner.py; edit echidna-mark.svg for logo geometry. -->
  <title id="cover-title">Echidna — Local Vulnerability Research Agent</title>
  <desc id="cover-description">An ivory butterfly and flowing E on ink black. Question. Observe. Verify.</desc>
  <rect width="1280" height="400" rx="24" fill="#19171f"/>
  <path d="M408 76V304M64 350H1216" stroke="#403b49"/>
  {logo}
  <text x="470" y="94" fill="#a697c3" font-family="Arial, sans-serif" font-size="11" letter-spacing="4">A QUIET CURIOSITY.</text>
  <text x="464" y="207" fill="#ece6db" font-family="Georgia, 'Times New Roman', serif" font-size="106" letter-spacing="-3">Echidna</text>
  <text x="470" y="253" fill="#b1a9b6" font-family="Arial, sans-serif" font-size="24">Local Vulnerability Research Agent</text>
  <text x="470" y="299" fill="#ece6db" font-family="Arial, sans-serif" font-size="15" letter-spacing="2">Question. Observe. Verify.</text>
  <text x="64" y="377" fill="#b1a9b6" font-family="Arial, sans-serif" font-size="10" letter-spacing="2">LOCAL-FIRST / SINGLE-USER</text>
  <text x="1216" y="377" text-anchor="end" fill="#a697c3" font-family="Arial, sans-serif" font-size="10" letter-spacing="2">RUST / CLI</text>
</svg>
'''
    (directory / "readme-banner.svg").write_text(banner, encoding="utf-8")


if __name__ == "__main__":
    main()
